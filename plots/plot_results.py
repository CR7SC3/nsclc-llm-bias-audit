# ─── Figure 5: Disparity heatmap (reference = no_demographics) ───────────────
#
# Using no_demographics as the control answers a cleaner scientific question:
# "Does telling the model a patient's demographics change guideline adherence,
#  and in which direction?"  All 5 demographic groups (including white_male_private)
# are compared against the demographically-neutral prompt.

# Groups shown in Fig 5 — all named variants, no_demographics is the reference
_FIG5_GROUPS = [
    "white_male_private",
    "black_male_medicaid",
    "black_female_medicaid",
    "latina_female_uninsured",
    "asian_female_medicare",
]


def _load_detail(slug: str) -> pd.DataFrame | None:
    """Load concordance detail CSV for a model slug."""
    path = ANALYSIS_DIR / f"{_csv_prefix(slug)}_concordance_detail.csv"
    if not path.exists():
        print(f"[warn] Missing detail CSV: {path}")
        return None
    return pd.read_csv(path)


def _downgrades_vs_no_demo(detail_df: pd.DataFrame) -> dict[str, int]:
    """Count cases where no_demographics is concordant but each other variant is not."""
    # Pivot: case_id × variant → concordant (NaN = not scoreable)
    pivot = detail_df.pivot_table(
        index="case_id", columns="variant", values="concordant", aggfunc="first"
    )
    ref = "no_demographics"
    if ref not in pivot.columns:
        return {}
    counts = {}
    for v in _FIG5_GROUPS:
        if v not in pivot.columns:
            counts[v] = 0
            continue
        # Cases where reference is concordant (1) and variant is not (0)
        mask = (pivot[ref] == 1) & (pivot[v] == 0)
        counts[v] = int(mask.sum())
    return counts


def fig5_heatmap(conc: dict, fmt: str) -> None:
    model_labels = list(MODELS.values())
    group_labels = [GROUP_LABELS[v] for v in _FIG5_GROUPS]
    model_slugs  = list(MODELS.keys())

    n_models = len(MODELS)
    n_groups = len(_FIG5_GROUPS)

    disp_matrix = np.full((n_models, n_groups), np.nan)
    dg_matrix   = np.full((n_models, n_groups), np.nan)

    for i, slug in enumerate(model_slugs):
        df = conc.get(slug)
        if df is None:
            continue

        # Disparity vs. no_demographics
        ref_rate = df.loc["no_demographics", "concordance_rate"] if "no_demographics" in df.index else np.nan
        for j, v in enumerate(_FIG5_GROUPS):
            if v not in df.index:
                continue
            disp_matrix[i, j] = (df.loc[v, "concordance_rate"] - ref_rate) * 100

        # Downgrades vs. no_demographics (recomputed from detail CSV)
        detail = _load_detail(slug)
        if detail is not None:
            dg = _downgrades_vs_no_demo(detail)
            for j, v in enumerate(_FIG5_GROUPS):
                dg_matrix[i, j] = dg.get(v, 0)

    fig, axes = plt.subplots(1, 2, figsize=(14, 3.4))

    # ── Left: concordance disparity heatmap ───────────────────────────────────
    ax = axes[0]
    vmax = max(abs(np.nanmin(disp_matrix)), abs(np.nanmax(disp_matrix)), 2)
    im = ax.imshow(disp_matrix, cmap="RdBu", vmin=-vmax, vmax=vmax, aspect="auto")
    cbar = fig.colorbar(im, ax=ax, shrink=0.85, pad=0.02)
    cbar.set_label("Disparity vs.\nno-demo control (pp)", fontsize=7.5)
    cbar.ax.tick_params(labelsize=7)
    ax.set_xticks(range(n_groups))
    ax.set_xticklabels(group_labels, fontsize=7.5)
    ax.set_yticks(range(n_models))
    ax.set_yticklabels(model_labels, fontsize=8.5)

    # Highlight the white_male_private column (first column) with a border
    for spine in ["top", "bottom", "left", "right"]:
        ax.spines[spine].set_visible(True)
    ax.add_patch(plt.Rectangle((-0.5, -0.5), 1, n_models, fill=False,
                                edgecolor="black", lw=2.0, clip_on=False, zorder=5))

    for ii in range(n_models):
        for jj in range(n_groups):
            v = disp_matrix[ii, jj]
            if not np.isnan(v):
                color = "white" if abs(v) > vmax * 0.55 else "black"
                ax.text(jj, ii, f"{v:+.1f}pp", ha="center", va="center",
                        fontsize=8, color=color, fontweight="bold")

    ax.set_title(
        "Concordance Disparity vs. No-Demographics Control\n"
        "Positive = adding demographics improves adherence; "
        "negative = worsens it",
        pad=8, fontsize=9
    )
    ax.text(-0.5, n_models + 0.1, "⬛ = white male reference",
            fontsize=7, va="bottom", color="#444444")

    # ── Right: downgrade count heatmap ────────────────────────────────────────
    ax2 = axes[1]
    vmax2 = max(np.nanmax(dg_matrix), 1)
    im2 = ax2.imshow(dg_matrix, cmap="YlOrRd", vmin=0, vmax=vmax2, aspect="auto")
    cbar2 = fig.colorbar(im2, ax=ax2, shrink=0.85, pad=0.02)
    cbar2.set_label("Downgrade count\nvs. no-demo control", fontsize=7.5)
    cbar2.ax.tick_params(labelsize=7)
    ax2.set_xticks(range(n_groups))
    ax2.set_xticklabels(group_labels, fontsize=7.5)
    ax2.set_yticks(range(n_models))
    ax2.set_yticklabels(model_labels, fontsize=8.5)
    ax2.add_patch(plt.Rectangle((-0.5, -0.5), 1, n_models, fill=False,
                                 edgecolor="black", lw=2.0, clip_on=False, zorder=5))

    for ii in range(n_models):
        for jj in range(n_groups):
            v = dg_matrix[ii, jj]
            if not np.isnan(v):
                color = "white" if v > vmax2 * 0.6 else "black"
                ax2.text(jj, ii, f"{int(v)}", ha="center", va="center",
                         fontsize=8, color=color, fontweight="bold")

    ax2.set_title(
        "Cases Where No-Demographics Prompt Is Concordant\nbut Named-Demographic Variant Is Not",
        pad=8, fontsize=9
    )

    fig.suptitle(
        "Cross-Model Summary — No-Demographics as Control  "
        f"(n = 165 cases × 6 variants; {N_SCOREABLE} NCCN-scoreable)\n"
        "Question: Does naming a patient's demographics change guideline adherence?",
        y=1.04, fontsize=10
    )
    fig.tight_layout()
    _save(fig, "fig5_summary_heatmap", fmt)


# ─── Figure 6: Cross-model summary table (visual) ────────────────────────────

def fig6_summary_table(conc: dict, flip: dict, fmt: str) -> None:
    rows = []
    for slug, label in MODELS.items():
        df_c = conc.get(slug)
        df_f = flip.get(slug)
        if df_c is None: continue
        ref_rate = df_c.loc["white_male_private", "concordance_rate"] if "white_male_private" in df_c.index else np.nan
        max_disp = min(
            df_c.loc[v, "disparity"] for v in MINORITY_VARIANTS if v in df_c.index
        )
        total_dg = sum(
            int(df_c.loc[v, "downgrade_count"]) for v in MINORITY_VARIANTS if v in df_c.index
        )
        mean_flip = np.mean([
            df_f.loc[v, "flip_rate"] for v in MINORITY_VARIANTS if v in df_f.index
        ]) if df_f is not None else np.nan
        rows.append({
            "Model": label,
            "Reference\nconcordance": f"{ref_rate:.1%}",
            "Worst-case\ndisparity": f"{max_disp:+.1%}",
            "Total\ndowngrades": str(total_dg),
            "Mean\nflip rate": f"{mean_flip:.1%}" if not np.isnan(mean_flip) else "—",
            "Homogeneity\np (concordance)": "0.882" if slug == "gpt-4o" else ("0.578" if slug == "gemini-2.5-flash" else "0.996"),
        })

    fig, ax = plt.subplots(figsize=(11, 2.4))
    ax.axis("off")
    col_labels = list(rows[0].keys())
    cell_data  = [[row[c] for c in col_labels] for row in rows]
    row_colors = [[MODEL_COLORS[slug] + "33"] * len(col_labels)
                  for slug in MODELS if slug in conc]

    tbl = ax.table(
        cellText=cell_data,
        colLabels=col_labels,
        cellLoc="center",
        loc="center",
        cellColours=row_colors,
    )
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(9)
    tbl.scale(1, 2.0)

    for (r, c), cell in tbl.get_celld().items():
        if r == 0:
            cell.set_facecolor("#444444")
            cell.set_text_props(color="white", fontweight="bold")
        cell.set_edgecolor("#dddddd")

    ax.set_title(
        "Cross-Model Summary — Structured NSCLC Dataset  (n=165 cases)",
        pad=14, fontsize=11, fontweight="bold"
    )
    fig.tight_layout()
    _save(fig, "fig6_summary_table", fmt)


# ─── Save helper ─────────────────────────────────────────────────────────────

def _save(fig: plt.Figure, name: str, fmt: str) -> None:
    path = FIGURES_DIR / f"{name}.{fmt}"
    fig.savefig(path, dpi=300, bbox_inches="tight")
    print(f"Saved: {path}")
    plt.close(fig)


# ─── Entry point ─────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(description="Generate EquityGUIDE publication figures.")
    parser.add_argument("--format", choices=["pdf", "png", "svg"], default="pdf",
                        help="Output format (default: pdf)")
    args = parser.parse_args()

    FIGURES_DIR.mkdir(parents=True, exist_ok=True)

    conc = load_concordance()
    flip = load_flip_rates()

    print(f"Concordance data loaded for : {list(conc.keys())}")
    print(f"Flip rate data loaded for   : {list(flip.keys())}")
    print()

    fig1_concordance_rates(conc, args.format)
    fig2_concordance_disparity(conc, args.format)
    fig3_guideline_downgrades(conc, args.format)
    fig4_flip_rates(flip, args.format)
    fig5_heatmap(conc, args.format)
    fig6_summary_table(conc, flip, args.format)

    print(f"\nAll figures saved to {FIGURES_DIR}/")


if __name__ == "__main__":
    main()
