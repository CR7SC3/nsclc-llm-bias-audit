# ─── Data loading ────────────────────────────────────────────────────────────

def _csv_prefix(slug: str) -> str:
    return SUBSET if slug == "gemini-2.5-flash" else f"{SUBSET}_{slug}"


def _wilson_ci(concordant: int, n: int) -> tuple[float, float]:
    if n == 0:
        return 0.0, 0.0
    z = 1.959964  # 97.5th percentile of standard normal
    p = concordant / n
    denom = 1 + z**2 / n
    centre = (p + z**2 / (2 * n)) / denom
    margin = z * np.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / denom
    return float(max(0.0, centre - margin)), float(min(1.0, centre + margin))


def load_concordance() -> dict[str, pd.DataFrame]:
    dfs: dict[str, pd.DataFrame] = {}
    for slug in MODELS:
        path = ANALYSIS_DIR / f"{_csv_prefix(slug)}_concordance_rates.csv"
        if not path.exists():
            print(f"[warn] Missing concordance CSV: {path}")
            continue
        df = pd.read_csv(path)
        df["n"] = df["concordant"] + df["non_concordant"]
        ci = [_wilson_ci(row["concordant"], row["n"]) for _, row in df.iterrows()]
        df["ci_low"]  = [c[0] for c in ci]
        df["ci_high"] = [c[1] for c in ci]
        dfs[slug] = df.set_index("variant")
    return dfs


def load_flip_rates() -> dict[str, pd.DataFrame]:
    dfs: dict[str, pd.DataFrame] = {}
    for slug in MODELS:
        path = ANALYSIS_DIR / f"{_csv_prefix(slug)}_flip_rates.csv"
        if not path.exists():
            print(f"[warn] Missing flip rate CSV: {path}")
            continue
        dfs[slug] = pd.read_csv(path).set_index("variant")
    return dfs


# ─── Shared helpers ──────────────────────────────────────────────────────────

def _bar_setup(n_models: int, n_groups: int, width: float = 0.24):
    x = np.arange(n_groups)
    offsets = np.linspace(-(n_models - 1) / 2, (n_models - 1) / 2, n_models) * width
    return x, offsets, width


def _grouped_bars(ax, models, values_fn, x, offsets, width, with_yerr=False, yerr_fn=None):
    for i, (slug, label) in enumerate(models.items()):
        vals = values_fn(slug)
        if vals is None:
            continue
        kwargs = dict(label=label, color=MODEL_COLORS[slug], alpha=0.88, zorder=3)
        if with_yerr and yerr_fn:
            err = yerr_fn(slug)
            kwargs.update(
                yerr=err, capsize=3,
                error_kw={"linewidth": 0.8, "ecolor": "#333333", "alpha": 0.7}
            )
        ax.bar(x + offsets[i], vals, width, **kwargs)


# ─── Figure 1: Concordance rates ─────────────────────────────────────────────

def fig1_concordance_rates(conc: dict, fmt: str) -> None:
    fig, ax = plt.subplots(figsize=(11, 5))

    x, offsets, w = _bar_setup(len(MODELS), len(VARIANTS))

    def vals(slug):
        df = conc.get(slug)
        if df is None: return None
        return [df.loc[v, "concordance_rate"] if v in df.index else np.nan for v in VARIANTS]

    def yerr(slug):
        df = conc.get(slug)
        if df is None: return None
        lo = [df.loc[v, "ci_low"]  for v in VARIANTS]
        hi = [df.loc[v, "ci_high"] for v in VARIANTS]
        r  = vals(slug)
        return [[rv - lv for rv, lv in zip(r, lo)],
                [hv - rv for hv, rv in zip(hi, r)]]

    _grouped_bars(ax, MODELS, vals, x, offsets, w, with_yerr=True, yerr_fn=yerr)

    # Dashed separator between reference and minority groups
    ax.axvline(0.5, color="black", lw=0.7, ls="--", alpha=0.35, zorder=0)
    ax.text(0.5, 0.415, "← Reference", fontsize=7.5, color="gray", ha="center")

    ax.set_ylim(0.40, 1.04)
    ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda y, _: f"{y:.0%}"))
    ax.set_ylabel("NCCN guideline concordance rate")
    ax.set_xticks(x)
    ax.set_xticklabels([GROUP_LABELS[v] for v in VARIANTS])
    ax.legend(loc="upper right", framealpha=0.92)
    ax.set_title(
        "NCCN Guideline Concordance by Demographic Variant and Model\n"
        "Structured NSCLC cases  (n = 165 cases × 6 variants; bars show 95% Wilson CI)",
        pad=9
    )
    ax.text(
        0.99, 0.02,
        "All homogeneity tests: p > 0.57 (ns, Bonferroni-corrected)",
        transform=ax.transAxes, ha="right", va="bottom",
        fontsize=7.5, color="gray", style="italic"
    )
    ax.yaxis.grid(True, lw=0.4, alpha=0.5, zorder=0)

    fig.tight_layout()
    _save(fig, "fig1_concordance_rates", fmt)


# ─── Figure 2: Concordance disparity (delta from reference) ──────────────────

def fig2_concordance_disparity(conc: dict, fmt: str) -> None:
    fig, ax = plt.subplots(figsize=(9.5, 4.5))

    x, offsets, w = _bar_setup(len(MODELS), len(MINORITY_VARIANTS))

    def vals(slug):
        df = conc.get(slug)
        if df is None: return None
        return [df.loc[v, "disparity"] * 100 if v in df.index else np.nan
                for v in MINORITY_VARIANTS]

    _grouped_bars(ax, MODELS, vals, x, offsets, w)

    ax.axhline(0, color="black", lw=1.0)
    ax.axhspan(-25, 0, alpha=0.04, color="#CC0000", zorder=0)

    ax.set_ylabel("Concordance disparity vs. white male (private ins.)  (pp)")
    ax.set_xticks(x)
    ax.set_xticklabels([GROUP_LABELS[v] for v in MINORITY_VARIANTS])
    ax.legend(framealpha=0.92)
    ax.set_title(
        "Concordance Disparity from White Male Reference\n"
        "Negative values = lower guideline adherence for minority variant",
        pad=9
    )
    ax.yaxis.grid(True, lw=0.4, alpha=0.5, zorder=0)

    # Annotate each bar with its p-value symbol
    for i, (slug, _) in enumerate(MODELS.items()):
        df = conc.get(slug)
        if df is None: continue
        for j, v in enumerate(MINORITY_VARIANTS):
            if v not in df.index: continue
            p = df.loc[v, "p_value_two_sided"]
            disp = df.loc[v, "disparity"] * 100
            try:
                p_val = float(p)
                sym = "***" if p_val < 0.001 else "**" if p_val < 0.01 else "*" if p_val < 0.05 else ""
            except (ValueError, TypeError):
                sym = ""
            if sym:
                ax.text(x[j] + offsets[i], disp + (0.4 if disp >= 0 else -0.8),
                        sym, ha="center", va="bottom", fontsize=7)

    fig.tight_layout()
    _save(fig, "fig2_concordance_disparity", fmt)


# ─── Figure 3: Guideline downgrades ──────────────────────────────────────────

def fig3_guideline_downgrades(conc: dict, fmt: str) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))

    x, offsets, w = _bar_setup(len(MODELS), len(MINORITY_VARIANTS))

    # Left panel: raw counts
    ax = axes[0]

    def counts(slug):
        df = conc.get(slug)
        if df is None: return None
        return [int(df.loc[v, "downgrade_count"]) if v in df.index else 0
                for v in MINORITY_VARIANTS]

    _grouped_bars(ax, MODELS, counts, x, offsets, w)
    ax.set_ylabel("Guideline downgrade count")
    ax.set_xticks(x); ax.set_xticklabels([GROUP_LABELS[v] for v in MINORITY_VARIANTS])
    ax.legend(framealpha=0.92)
    ax.set_title("Raw downgrade count", pad=7)
    ax.yaxis.grid(True, lw=0.4, alpha=0.5, zorder=0)

    # Right panel: downgrade rate (per scoreable case)
    ax2 = axes[1]

    def rates(slug):
        df = conc.get(slug)
        if df is None: return None
        return [int(df.loc[v, "downgrade_count"]) / N_SCOREABLE if v in df.index else 0
                for v in MINORITY_VARIANTS]

    _grouped_bars(ax2, MODELS, rates, x, offsets, w)
    ax2.yaxis.set_major_formatter(plt.FuncFormatter(lambda y, _: f"{y:.0%}"))
    ax2.set_ylabel("Downgrade rate (% of scoreable cases)")
    ax2.set_xticks(x); ax2.set_xticklabels([GROUP_LABELS[v] for v in MINORITY_VARIANTS])
    ax2.set_title("Downgrade rate", pad=7)
    ax2.yaxis.grid(True, lw=0.4, alpha=0.5, zorder=0)

    fig.suptitle(
        "Guideline Downgrades: Cases Where White Male Variant Receives Concordant Recommendation "
        "but Matched Minority Variant Does Not\n"
        f"(n = {N_SCOREABLE} NCCN-scoreable cases)",
        y=1.01, fontsize=10.5
    )
    fig.tight_layout()
    _save(fig, "fig3_guideline_downgrades", fmt)


